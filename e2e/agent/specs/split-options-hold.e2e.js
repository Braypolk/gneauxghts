import { browser, $, $$, expect } from '@wdio/globals';

// Recorded through the WDIO session loop and reduced to the independent workflow.
describe('held split options shortcut', () => {
  it('shows defaults, records modifier-only remaps, and honors removal and reset', async () => {
    await browser.setWindowSize(1440, 1000);
    await browser.url('/__gneauxghts_e2e_reset');
    await browser.execute(() => { localStorage.clear(); sessionStorage.clear(); });
    await browser.url('/');
    await expect($('[data-testid="note-title"]')).toHaveValue('Alpha note');
    const send = async (type, key, code, modifiers = {}) => browser.execute((type, key, code, modifiers) => {
      document.activeElement.dispatchEvent(new KeyboardEvent(type, { key, code, bubbles: true, cancelable: true, ...modifiers }));
    }, type, key, code, modifiers);
    const cue = () => $('.split-pane-control');
    const expanded = 'split-pane-control--split';
    await $('.cm-content').click();
    await send('keydown', 'Alt', 'AltLeft', { altKey: true });
    await expect(cue()).toHaveAttribute('class', expect.stringContaining(expanded));
    await send('keyup', 'Alt', 'AltLeft');
    await expect(cue()).not.toHaveAttribute('class', expect.stringContaining(expanded));
    await send('keydown', 'Shift', 'ShiftLeft', { metaKey: true, shiftKey: true });
    await expect(cue()).toHaveAttribute('class', expect.stringContaining(expanded));
    await send('keyup', 'Shift', 'ShiftLeft', { metaKey: true });
    await expect(cue()).not.toHaveAttribute('class', expect.stringContaining(expanded));
    await browser.url('/settings');
    await $('button=Keyboard shortcuts').click();
    await $('input[aria-label="Filter shortcuts"]').setValue('Show Split Options');
    await expect($$('tr[data-shortcut-id="showSplitOptions"]')).toBeElementsArrayOfSize(1);
    await expect($$('tr[data-shortcut-id="showSplitOptions"] .binding-button')).toBeElementsArrayOfSize(2);
    await expect($('button[aria-label="Change Show Split Options shortcut, Option"]')).toBeDisplayed();
    await expect($('button[aria-label="Change Show Split Options shortcut, Cmd + Shift"]')).toBeDisplayed();
    await $('button[aria-label="Change Show Split Options shortcut, Option"]').click();
    await expect($('[role="dialog"]')).toHaveText(expect.stringContaining('Hold your desired modifiers'));
    await send('keydown', 'Shift', 'ShiftLeft', { ctrlKey: true, shiftKey: true });
    await expect($('[data-testid="shortcut-recording"] span[aria-label]')).toHaveAttribute('aria-label', 'Ctrl + Shift');
    await send('keyup', 'Shift', 'ShiftLeft');
    await send('keydown', 'Enter', 'Enter');
    await expect($('button[aria-label="Change Show Split Options shortcut, Ctrl + Shift"]')).toBeDisplayed();
    await $('button[aria-label="Remove Cmd + Shift from Show Split Options"]').click();
    await expect($$('tr[data-shortcut-id="showSplitOptions"]')).toBeElementsArrayOfSize(1);
    await expect($$('tr[data-shortcut-id="showSplitOptions"] .binding-button')).toBeElementsArrayOfSize(1);
    await browser.refresh();
    await $('button=Keyboard shortcuts').click();
    await $('input[aria-label="Filter shortcuts"]').setValue('Show Split Options');
    await expect($('button[aria-label="Change Show Split Options shortcut, Ctrl + Shift"]')).toBeDisplayed();
    await browser.url('/');
    await expect($('[data-testid="note-title"]')).toHaveValue('Alpha note');
    await $('.cm-content').click();
    await send('keydown', 'Alt', 'AltLeft', { altKey: true });
    await expect(cue()).not.toHaveAttribute('class', expect.stringContaining(expanded));
    await send('keyup', 'Alt', 'AltLeft');
    await send('keydown', 'Shift', 'ShiftLeft', { metaKey: true, shiftKey: true });
    await expect(cue()).not.toHaveAttribute('class', expect.stringContaining(expanded));
    await send('keyup', 'Shift', 'ShiftLeft');
    await send('keydown', 'Shift', 'ShiftLeft', { ctrlKey: true, shiftKey: true });
    await expect(cue()).toHaveAttribute('class', expect.stringContaining(expanded));
    await send('keyup', 'Shift', 'ShiftLeft');
    await expect(cue()).not.toHaveAttribute('class', expect.stringContaining(expanded));
    await browser.url('/settings');
    await $('button=Keyboard shortcuts').click();
    await $('input[aria-label="Filter shortcuts"]').setValue('Show Split Options');
    await $('button[aria-label="Remove Ctrl + Shift from Show Split Options"]').click();
    await expect($('tr[data-shortcut-id="showSplitOptions"]')).toHaveText(expect.stringContaining('Unassigned'));
    await browser.url('/');
    await expect($('[data-testid="note-title"]')).toHaveValue('Alpha note');
    await $('.cm-content').click();
    await send('keydown', 'Shift', 'ShiftLeft', { ctrlKey: true, shiftKey: true });
    await expect(cue()).not.toHaveAttribute('class', expect.stringContaining(expanded));
    await send('keyup', 'Shift', 'ShiftLeft');
    await browser.url('/settings');
    await $('button=Keyboard shortcuts').click();
    await $('input[aria-label="Filter shortcuts"]').setValue('Show Split Options');
    await $('button[aria-label="Reset Show Split Options to default"]').click();
    await expect($('button[aria-label="Change Show Split Options shortcut, Option"]')).toBeDisplayed();
    await expect($('button[aria-label="Change Show Split Options shortcut, Cmd + Shift"]')).toBeDisplayed();
  });
});
